#!/usr/bin/env python3
"""build_kernel.py -- portable build for itp_env (the C++ kernel + nanobind bindings).

Every prior build command in this whole project's history hardcoded Linux paths
(/usr/local/lib/python3.12/dist-packages/nanobind/..., /usr/include/python3.12) and called `g++`
directly -- fine for the Linux sandbox this project was developed in, but this is the script meant
to be run on real hardware, likely a Mac, where none of those paths exist and the default compiler
is Apple clang, not g++. This script finds everything through PORTABLE introspection instead:
nanobind's own include_dir()/source_dir() (pure Python, package-relative, works identically on any
OS), sysconfig for Python's own headers and the platform-correct extension suffix, and a
platform.system() check for the one place object-file-to-shared-library flags genuinely differ
(macOS needs -bundle -undefined dynamic_lookup where Linux takes -shared). Verified end to end (this
exact code path, not the old hardcoded command) against the full regression suite before this was
considered done -- see BUILD_AND_RUN.md.

Usage: python3 build_kernel.py [--verbose]
"""
from __future__ import annotations

import os
import platform
import shutil
import subprocess
import sys
import sysconfig
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "src" / "c++" / "reference"          # the sources of the previous generation's kernel (frozen)


def find_compiler() -> str:
    """$CXX if set (respects an explicit user choice, e.g. a newer clang++ installed alongside an
    older system default); otherwise the first of a portable-name list that actually exists.
    Deliberately never hardcodes 'g++': on macOS that name may not exist at all, or may itself be a
    thin alias for clang -- 'c++' is the POSIX-conventional, always-present name for whichever C++
    compiler a system considers its default, and is preferred first for exactly that reason."""
    if os.environ.get("CXX"):
        return os.environ["CXX"]
    for name in ("c++", "clang++", "g++"):
        if shutil.which(name):
            return name
    raise RuntimeError("No C++ compiler found (tried $CXX, c++, clang++, g++). "
                       "On macOS: install Xcode Command Line Tools (`xcode-select --install`). "
                       "On Linux: install g++ or clang++ via your package manager.")


def python_include_dir() -> Path:
    """Python's own headers (Python.h and friends). Tries sysconfig first (portable, no shelling
    out); if Python.h isn't actually there, falls back to `python3-config --includes`, which is
    generated by the actual Python build and sometimes resolves correctly where sysconfig's
    reported path does not (seen in practice with macOS's Command Line Tools Python -- see the
    RuntimeError below for why). Raises with a specific, actionable diagnosis rather than letting a
    confusing 'Python.h not found' surface from deep inside a real nanobind-including compile."""
    candidates = [Path(sysconfig.get_paths()["include"])]
    py_config = shutil.which("python3-config") or shutil.which(f"python{sys.version_info.major}.{sys.version_info.minor}-config")
    if py_config:
        r = subprocess.run([py_config, "--includes"], capture_output=True, text=True)
        if r.returncode == 0:
            for tok in r.stdout.split():
                if tok.startswith("-I"):
                    candidates.append(Path(tok[2:]))
    for c in candidates:
        if (c / "Python.h").is_file():
            return c
    tried = "\n  ".join(str(c) for c in candidates)
    raise RuntimeError(
        f"Python.h was not found in any of:\n  {tried}\n\n"
        f"This interpreter ({sys.executable}) does not have working development headers. On macOS, "
        f"this almost always means you're running the Command Line Tools' bundled Python "
        f"(/Library/Developer/CommandLineTools/usr/bin/python3) -- it runs Apple's own build "
        f"scripts and is not meant for building C extensions against; its headers are frequently "
        f"missing or misreported by its own sysconfig. The fix is a real, complete Python:\n"
        f"  brew install python@3.12\n"
        f"  /opt/homebrew/bin/python3.12 -m venv .venv && source .venv/bin/activate\n"
        f"  pip install torch numpy nanobind\n"
        f"  python3 build_kernel.py\n"
        f"(On Linux: install your distribution's -dev/-devel package, e.g. `apt install "
        f"python3-dev` or `dnf install python3-devel`.)")


def nanobind_paths() -> tuple[Path, Path, Path]:
    """(include_dir, source_dir, robin_map_include_dir) -- all three derived from nanobind's own
    Python-exposed, package-relative helpers (include_dir()/source_dir()) or a path relative to
    them (robin_map has no dedicated helper, but always lives at ext/robin_map/include next to
    nanobind's own include dir -- true on every platform, since it is just where pip unpacked the
    package, not an OS-specific location)."""
    try:
        import nanobind
    except ImportError:
        raise RuntimeError("nanobind is not installed in this Python environment. Run: "
                           "pip install nanobind") from None
    include_dir = Path(nanobind.include_dir())
    source_dir = Path(nanobind.source_dir())
    robin_map_dir = include_dir.parent / "ext" / "robin_map" / "include"
    if not robin_map_dir.is_dir():
        raise RuntimeError(f"expected robin_map headers at {robin_map_dir}, but that path does not "
                           f"exist -- nanobind's own packaging may have changed; check "
                           f"{include_dir.parent / 'ext'} for the actual location and adjust this "
                           f"script (this is the one place a directory layout is assumed rather than "
                           f"discovered through a nanobind-provided function).")
    return include_dir, source_dir, robin_map_dir


def shared_lib_flags() -> list[str]:
    """The one place object-file-to-loadable-extension flags genuinely differ by platform."""
    system = platform.system()
    if system == "Darwin":
        return ["-bundle", "-undefined", "dynamic_lookup"]
    if system == "Linux":
        return ["-shared"]
    if system == "Windows":
        raise RuntimeError("This project has not been built or tested on Windows. WSL2 (a Linux "
                           "environment) is the supported path there.")
    raise RuntimeError(f"Unrecognized platform.system() = {system!r}; add its shared-library flags "
                       f"here (Linux: -shared; macOS: -bundle -undefined dynamic_lookup) to proceed.")


def try_compile(cxx: str, std_flag: str, extra_include: Path) -> bool:
    """Whether `cxx` accepts `std_flag` at all, checked with a trivial C++23-flavored program
    (concepts + <expected>, both features this codebase relies on) before committing to a full,
    slow build -- fails fast with a clear reason instead of a wall of real-source errors if the
    installed compiler is too old."""
    probe = HERE / "_std_probe.cpp"
    probe.write_text(
        "#include <expected>\n#include <concepts>\n"
        "template<class T> concept Addable = requires(T a, T b) { a + b; };\n"
        "std::expected<int,int> f() { return 1; }\nint main() { return *f(); }\n"
    )
    try:
        r = subprocess.run([cxx, std_flag, f"-I{extra_include}", "-c", str(probe), "-o", "/dev/null"],
                           capture_output=True, text=True)
        return r.returncode == 0
    finally:
        probe.unlink(missing_ok=True)


def pick_std_flag(cxx: str) -> str:
    """Prefers -std=c++23; falls back to -std=c++2b for compilers (some Apple clang versions among
    them) that only recognize the pre-standardization spelling. Raises with a clear, actionable
    message if neither works, rather than surfacing a wall of unrelated-looking template errors
    from deep inside the real source files."""
    sysconfig_include = Path(sysconfig.get_paths()["include"])
    for flag in ("-std=c++23", "-std=c++2b"):
        if try_compile(cxx, flag, sysconfig_include):
            return flag
    raise RuntimeError(
        f"{cxx} accepts neither -std=c++23 nor -std=c++2b (both tried, both failed to compile a "
        f"trivial program using std::expected and concepts). This codebase needs a C++23-capable "
        f"compiler. On macOS: `xcode-select --install`, then `softwareupdate --list` to check for a "
        f"newer Command Line Tools version -- Xcode 15+ is recommended. On Linux: g++ 12+ or "
        f"clang++ 16+.")


def main() -> int:
    verbose = "--verbose" in sys.argv
    cxx = find_compiler()
    include_dir, source_dir, robin_map_dir = nanobind_paths()
    py_include = python_include_dir()
    ext_suffix = sysconfig.get_config_var("EXT_SUFFIX")
    if not ext_suffix:
        raise RuntimeError("sysconfig could not determine EXT_SUFFIX for this Python interpreter.")
    output = HERE / f"itp_env{ext_suffix}"

    std_flag = pick_std_flag(cxx)
    print(f"compiler:        {cxx}")
    print(f"C++ standard:    {std_flag}")
    print(f"platform:        {platform.system()} / {platform.machine()}")
    print(f"nanobind:        {include_dir.parent}")
    print(f"python headers:  {py_include}")
    print(f"output:          {output.name}")

    cmd = [
        cxx, std_flag, "-O2", "-fPIC", "-pthread",
        f"-I{include_dir}", f"-I{robin_map_dir}", f"-I{py_include}", f"-I{SRC}",
        *shared_lib_flags(),
        str(SRC / "itp_bindings.cpp"), str(source_dir / "nb_combined.cpp"),
        "-o", str(output),
    ]
    if verbose:
        print("\n" + " ".join(cmd) + "\n")
    t0 = __import__("time").perf_counter()
    r = subprocess.run(cmd, capture_output=not verbose, text=True)
    dt = __import__("time").perf_counter() - t0
    if r.returncode != 0:
        print(f"\nBUILD FAILED ({dt:.0f}s):\n", file=sys.stderr)
        if not verbose:
            print(r.stderr, file=sys.stderr)
        return 1
    print(f"\nBuild succeeded in {dt:.0f}s -> {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
